#!/usr/bin/env python3
"""Generate tokens.css from the Figma variables export (design-system/tokens.json).

Re-export from Figma, overwrite tokens.json, then run: python3 design-system/build-tokens.py
Each token Group/Name becomes --group-name, e.g. Page/Primary button -> --page-primary-button.
"""
import json, re, pathlib

root = pathlib.Path(__file__).resolve().parent
tokens = json.loads((root / 'tokens.json').read_text())
slug = lambda s: re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')

def colour(value):
    hex_ = value['hex'].lower()
    alpha = value.get('alpha', 1)
    return hex_ if alpha >= 1 else f"{hex_}{round(alpha * 255):02x}"

lines = []
def walk(node, path):
    if isinstance(node, dict) and '$value' in node:
        alias = node.get('$extensions', {}).get('com.figma.aliasData', {}).get('targetVariableName')
        value = colour(node['$value']) if node.get('$type') == 'color' else node['$value']
        lines.append(f"  --{'-'.join(map(slug, path))}: {value};" + (f" /* {alias} */" if alias else ''))
        return
    for key, child in node.items():
        if not key.startswith('$'):
            walk(child, path + [key])
walk(tokens, [])

(root.parent / 'tokens.css').write_text(
    "/* Generated by design-system/build-tokens.py from design-system/tokens.json. Do not edit by hand. */\n"
    ":root {\n" + "\n".join(lines) + "\n}\n")
print(f"Wrote {len(lines)} tokens to tokens.css")
